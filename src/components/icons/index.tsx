/** The app's icon props: `strokeWidth` picks Phosphor's light, regular or bold weight; a `fill` or `fill-current` draws the filled weight. */
export interface IconProps extends ComponentPropsWithoutRef<"svg"> {
  size?: number | string;
  strokeWidth?: number | string;
  color?: string;
}
export type IconType = ForwardRefExoticComponent<IconProps & RefAttributes<SVGSVGElement>>;

function weightOf(strokeWidth: IconProps["strokeWidth"], fill: string | undefined, className: string | undefined): IconWeight {
  if ((fill && fill !== "none") || className?.split(/s+/).includes("fill-current")) return "fill";
  const width = Number(strokeWidth ?? 1.75);
  return width < 1.4 ? "light" : width >= 2.25 ? "bold" : "regular";
}

function icon(Shape: Glyph, name: string): IconType {
  const Wrapped = forwardRef<SVGSVGElement, IconProps>(({ size = 24, strokeWidth, fill, className, ...rest }, ref) => (
    <Shape ref={ref} size={size} weight={weightOf(strokeWidth, fill, className)} className={cn("icon", `icon-${name}`, className)} {...rest} />
  ));
  Wrapped.displayName = name;
  return Wrapped;
}

